"""Ground-truth simulation: prove the gates discriminate skill from luck.

Everything produced here is **SYNTHETIC**. The numbers are generated by this
file from a fixed seed; they describe no real team, player, game or market and
must never be read as an NBA result. The purpose is a controlled experiment:
we know the true generating process, so we know whether a gate that passes or
fails is correct.

Five archetypes are generated, each with 3,000 bets:

  A  LUCKY       true edge 0%, but a hot streak is added so the realised ROI is
                 positive. A naive leaderboard ranks this near the top.
  B  SKILL        a real 3% edge on every bet, stable.
  C  OVERFIT      a strategy chosen from 60 tried on noise; its in-sample record
                 is excellent and its out-of-sample record is zero.
  D  CORRELATED   a two-leg parlay priced as if independent, where the legs are
                 positively correlated — looks +EV on the independence
                 assumption, is -EV in truth.
  E  LOWPOWER     a real 2% edge observed over only 40 bets.

The tests assert the gate verdicts, so a change that makes the gates lenient
breaks CI.
"""
from __future__ import annotations

import math

from .luck import Rng
from . import pricing

N_BETS = 3000
SEED = 20261105
PRICE = -110.0
BREAKEVEN = pricing.breakeven_probability(PRICE)   # 0.52381 at -110


def _bet(p_win: float, rng: Rng) -> tuple[float, int]:
    won = rng.random() < p_win
    return (pricing.american_to_decimal(PRICE) - 1.0 if won else -1.0), int(won)


def lucky_run(n: int = N_BETS, seed: int = SEED) -> dict:
    """Zero true edge, but the draw is favourable. Cumulative noise, not skill."""
    rng = Rng(seed)
    returns, outcomes = [], []
    for i in range(n):
        # a genuine 0-edge bettor at -110 wins 52.38% only if the price is fair;
        # here the true probability equals breakeven, so expected ROI is 0.
        r, o = _bet(BREAKEVEN, rng)
        returns.append(r)
        outcomes.append(o)
    wins = sum(outcomes)
    return {
        "id": "A_LUCKY",
        "label": "Lucky (true edge 0%)",
        "true_edge": 0.0,
        "n": n,
        "wins": wins,
        "win_rate": wins / n,
        "roi": sum(returns) / n,
        "per_bet_return": returns,
        "outcomes": outcomes,
        "probs": [BREAKEVEN] * n,
    }


def heater(n: int = 150, min_roi: float = 0.12, price: float = PRICE) -> dict:
    """Zero true edge, short sample, strongly positive realised ROI.

    This is the failure mode a leaderboard actually faces: not a long record
    that drifts to zero, but a 150-bet run that happens to land well. The seed
    is searched deterministically so the reported draw is reproducible and is
    the *first* qualifying seed, never hand-picked for a nicer story.
    """
    p = pricing.breakeven_probability(price)
    d = pricing.american_to_decimal(price)
    for seed in range(SEED, SEED + 200000):
        rng = Rng(seed)
        returns, outcomes = [], []
        for _ in range(n):
            won = rng.random() < p
            returns.append(d - 1.0 if won else -1.0)
            outcomes.append(int(won))
        roi = sum(returns) / n
        if roi >= min_roi:
            return {
                "id": "A_HEATER",
                "label": f"Heater (true edge 0%, n = {n}, lucky draw)",
                "true_edge": 0.0,
                "n": n,
                "seed_used": seed,
                "roi": roi,
                "wins": sum(outcomes),
                "win_rate": sum(outcomes) / n,
                "per_bet_return": returns,
                "outcomes": outcomes,
                "probs": [p] * n,
            }
    raise RuntimeError("no qualifying zero-edge heater found in the searched seeds")


def skill_run(edge: float = 0.03, n: int = N_BETS, seed: int = SEED + 1) -> dict:
    """A real, constant edge."""
    rng = Rng(seed)
    d = pricing.american_to_decimal(PRICE)
    p = (1.0 + edge) / d
    returns, outcomes = [], []
    for _ in range(n):
        r, o = _bet(p, rng)
        returns.append(r)
        outcomes.append(o)
    wins = sum(outcomes)
    return {
        "id": "B_SKILL",
        "label": "Skill (true edge 3%)",
        "true_edge": edge,
        "n": n,
        "wins": wins,
        "win_rate": wins / n,
        "roi": sum(returns) / n,
        "per_bet_return": returns,
        "outcomes": outcomes,
        "probs": [p] * n,
    }


def skill_full(edge: float = 0.05, n: int = 30000, seed: int = SEED + 5) -> dict:
    """A skill archetype carrying EVERY input a gate needs, to test the pass path.

    Real market loss never reaches zero, so the loss series here is a plausible
    stand-in with a small, consistent advantage (market 0.60, model 0.58 mean
    log loss) drawn around the true edge. It is SYNTHETIC. Its only purpose is
    to confirm that a strategy that satisfies the gates can actually qualify —
    a gate that nothing can pass is not a test, it is a wall.
    """
    rng = Rng(seed)
    d = pricing.american_to_decimal(PRICE)
    p = (1.0 + edge) / d
    returns, outcomes = [], []
    model_ll, market_ll = [], []
    for _ in range(n):
        won = rng.random() < p
        returns.append(d - 1.0 if won else -1.0)
        outcomes.append(int(won))
        model_ll.append(max(1e-9, 0.58 + 0.06 * _normal(rng)))
        market_ll.append(max(1e-9, 0.60 + 0.06 * _normal(rng)))
    return {
        "id": "F_SKILL_FULL",
        "label": f"Skill with full evidence (true edge {edge:.0%}, n = {n})",
        "true_edge": edge,
        "n": n,
        "roi": sum(returns) / n,
        "wins": sum(outcomes),
        "win_rate": sum(outcomes) / n,
        "per_bet_return": returns,
        "outcomes": outcomes,
        "probs": [min(0.99, max(0.01, p + 0.03 * _normal(rng))) for _ in range(n)],
        "model_logloss": model_ll,
        "market_logloss": market_ll,
        "evidence_bundle": True,
    }


def _normal(rng: Rng) -> float:
    """Box-Muller from the deterministic generator."""
    import math as _m

    u1 = max(1e-12, rng.random())
    u2 = rng.random()
    return _m.sqrt(-2.0 * _m.log(u1)) * _m.cos(2.0 * _m.pi * u2)


def overfit_family(n_strategies: int = 60, n: int = 400, seed: int = SEED + 2) -> dict:
    """Sixty zero-edge strategies; report the best in-sample one and its OOS record."""
    rng = Rng(seed)
    sequences = []
    for _ in range(n_strategies):
        returns = [_bet(BREAKEVEN, rng)[0] for _ in range(n)]
        sequences.append(returns)
    in_sample = [sum(s) / len(s) for s in sequences]
    best = max(range(n_strategies), key=lambda i: in_sample[i])

    oos_rng = Rng(seed + 999)
    oos = [[_bet(BREAKEVEN, oos_rng)[0] for _ in range(n)] for _ in range(n_strategies)]
    oos_means = [sum(s) / len(s) for s in oos]
    return {
        "id": "C_OVERFIT",
        "label": f"Overfit (best of {n_strategies} zero-edge strategies)",
        "n_strategies": n_strategies,
        "n": n,
        "best_index": best,
        "in_sample_roi_best": in_sample[best],
        "in_sample_roi_mean": sum(in_sample) / n_strategies,
        "oos_roi_best": oos_means[best],
        "oos_roi_mean": sum(oos_means) / n_strategies,
        "in_sample_sequences": sequences,
        "oos_sequences": oos,
    }


def correlated_parlay(rho: float = 0.35, n: int = N_BETS, seed: int = SEED + 3) -> dict:
    """Two legs priced at fair single-leg odds, booked as an independent parlay.

    Ground truth: the legs share a latent factor with correlation ``rho``, so the
    true joint probability is above the product of marginals when both legs are
    'over' events. The book prices the parlay as if independent, which means it
    *underpays*... but a model that assumes independence to *find* value will
    systematically overstate its edge.
    """
    rng = Rng(seed)
    p_leg = 0.55
    # The leg wins when its latent normal falls below the p_leg quantile, so
    # P(win) = p_leg exactly. Using Phi^-1(p_leg) as a lower bound instead would
    # make each leg a 45% event and understate the joint by 10 points.
    z_threshold = _norm_ppf(p_leg)
    fair_leg = -100.0 * p_leg / (1 - p_leg)      # fair price for a 55% leg
    product = p_leg * p_leg
    dec_parlay = pricing.american_to_decimal(fair_leg) ** 2

    wins_both = 0
    returns = []
    for _ in range(n):
        z = _norm_ppf(rng.random())
        e1 = math.sqrt(1 - rho) * _norm_ppf(rng.random()) + math.sqrt(rho) * z
        e2 = math.sqrt(1 - rho) * _norm_ppf(rng.random()) + math.sqrt(rho) * z
        both = (e1 < z_threshold) and (e2 < z_threshold)
        wins_both += int(both)
        returns.append(dec_parlay - 1.0 if both else -1.0)
    return {
        "id": "D_CORRELATED",
        "label": f"Correlated parlay (rho = {rho})",
        "rho_true": rho,
        "p_leg": p_leg,
        "p_joint_independent": product,
        "p_joint_true": wins_both / n,
        "n": n,
        "decimal_parlay_if_independent": dec_parlay,
        "ev_if_independent": product * dec_parlay - 1.0,
        "ev_true": (wins_both / n) * dec_parlay - 1.0,
        "realised_roi": sum(returns) / n,
        "per_bet_return": returns,
    }


def low_power_run(edge: float = 0.02, n: int = 40, seed: int = SEED + 4) -> dict:
    """A real edge seen through far too small a sample."""
    rng = Rng(seed)
    d = pricing.american_to_decimal(PRICE)
    p = (1.0 + edge) / d
    returns, outcomes = [], []
    for _ in range(n):
        r, o = _bet(p, rng)
        returns.append(r)
        outcomes.append(o)
    return {
        "id": "E_LOWPOWER",
        "label": f"Low power (true edge {edge}, n = {n})",
        "true_edge": edge,
        "n": n,
        "roi": sum(returns) / n,
        "per_bet_return": returns,
        "outcomes": outcomes,
        "probs": [p] * n,
    }


def _norm_ppf(p: float) -> float:
    from .luck import norm_ppf

    return norm_ppf(min(max(p, 1e-9), 1 - 1e-9))


def run_all() -> dict:
    return {
        "A_LUCKY": lucky_run(),
        "A_HEATER": heater(),
        "B_SKILL": skill_run(),
        "C_OVERFIT": overfit_family(),
        "D_CORRELATED": correlated_parlay(),
        "E_LOWPOWER": low_power_run(),
        "F_SKILL_FULL": skill_full(),
    }
