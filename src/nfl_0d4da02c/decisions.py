def main() -> int:
    os.makedirs(DATA, exist_ok=True)

    with open(os.path.join(DATA, "suggestions.csv"), "w", newline="",
              encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["suggestion_id", "title", "category", "what_it_improves",
                    "evidence_needed", "blocking_gate", "req_ids", "note",
                    "owner_decision", "decision_date"])
        for s in SUGGESTIONS:
            w.writerow(list(s) + ["", ""])
    print(f"wrote suggestions.csv: {len(SUGGESTIONS)} rows")

    with open(os.path.join(DATA, "suggestion_options.csv"), "w", newline="",
              encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["option_id", "suggestion_id", "path_label", "what_it_does", "cost",
                    "risk", "evidence_needed", "clearing_number",
                    "owner_choice", "choice_date"])
        for o in OPTIONS:
            w.writerow(list(o) + ["", ""])
    print(f"wrote suggestion_options.csv: {len(OPTIONS)} rows")

    with open(os.path.join(DATA, "qia.csv"), "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["question_id", "question", "what_we_have", "what_we_lack", "answer",
                    "answer_status", "discovery_route", "blocking_gate", "source_url"])
        w.writerows([list(q) for q in QIA])
    print(f"wrote qia.csv: {len(QIA)} rows")

    with open(os.path.join(DATA, "information_gaps.csv"), "w", newline="",
              encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["gap_id", "missing_dataset", "why_it_blocks", "acquisition_route",
                    "clearing_number", "official_host", "status", "req_ids_blocked",
                    "source_url"])
        w.writerows([list(g) for g in GAPS])
    print(f"wrote information_gaps.csv: {len(GAPS)} rows")

    with open(os.path.join(DATA, "claim_checks.csv"), "w", newline="",
              encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["check_id", "claim", "where_it_was_published",
                    "recomputed_this_session", "result", "note"])
        w.writerows([list(c) for c in CLAIM_CHECKS])
    print(f"wrote claim_checks.csv: {len(CLAIM_CHECKS)} rows")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
