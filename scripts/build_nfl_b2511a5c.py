#!/usr/bin/env python3
"""Build the nfl_b2511a5c pages (docs/nfl-b2511a5c/*.html) from the registers in data/nfl_b2511a5c/.

Zero arguments, zero network, no clock: every count is recomputed from the CSVs and raw captures at build time,
so re-running the build changes no byte. Verified by scripts/check_nfl_b2511a5c.py.

Source-link rule (the owner's brief: every table row needs a source link to an official site):
  a row is rendered in a table only if it links to an official nfl.com read; rows whose only evidence is a
  club website or a repo file are rendered in a separate, labelled list.
"""
from __future__ import annotations

import csv
import html
import os
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
DATA = os.path.join(REPO, "data", "nfl_b2511a5c")
DOCS = os.path.join(REPO, "docs", "nfl-b2511a5c")
REPO_URL = "https://github.com/sassnarep3-star/Own6/blob/main"
BUILD_NOTE = "generated by scripts/build_nfl_b2511a5c.py from data/nfl_b2511a5c; no clock, no network"

NAV = [
    ("index.html", "Start here"),
    ("week11.html", "Week 11 slate"),
    ("claims.html", "Claim checks"),
    ("reads.html", "Official reads"),
    ("club-depth.html", "Club-site reads"),
    ("flagged.html", "Flagged for Review"),
    ("suggestions.html", "Suggestions"),
    ("questions.html", "Questions"),
    ("sources.html", "Sources"),
]


def load(name: str) -> list[dict]:
    with open(os.path.join(DATA, name), encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def esc(s: object) -> str:
    return html.escape("" if s is None else str(s), quote=True)


def link(url: str, label: str | None = None) -> str:
    return f'<a href="{esc(url)}">{esc(label or url)}</a>'


def page(title: str, active: str, body: str) -> str:
    nav = "".join(
        f'<a class="{"on" if f == active else ""}" href="{f}">{esc(label)}</a>' for f, label in NAV
    )
    return f"""<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{esc(title)} | NFL official-source re-check, 2026-11-18</title>
<style>
 body{{font:15px/1.5 -apple-system,Segoe UI,Roboto,sans-serif;margin:0;color:#12233b;background:#f6f8fb}}
 header{{background:#0b2545;color:#fff;padding:18px 22px}} header h1{{margin:0;font-size:20px}}
 header p{{margin:4px 0 0;opacity:.85;font-size:13px}}
 nav{{display:flex;flex-wrap:wrap;gap:2px;background:#13315c;padding:6px 10px}}
 nav a{{color:#cfe0f5;text-decoration:none;padding:5px 9px;border-radius:4px;font-size:12.5px}}
 nav a.on,nav a:hover{{background:#ee6c4d;color:#fff}}
 main{{max-width:1240px;margin:0 auto;padding:18px}}
 section{{background:#fff;border:1px solid #dfe6f0;border-radius:8px;padding:14px 16px;margin:14px 0}}
 h2{{font-size:17px;margin:4px 0 10px}} h3{{font-size:14.5px;margin:12px 0 6px}}
 .table-wrap{{overflow-x:auto}} table{{border-collapse:collapse;width:100%;font-size:12.5px}}
 th,td{{border:1px solid #e3e9f2;padding:5px 7px;text-align:left;vertical-align:top}} th{{background:#eef3fa}}
 a{{color:#0b5394}} code{{font-size:12px;word-break:break-all}}
 .grid{{display:grid;grid-template-columns:repeat(auto-fit,minmax(190px,1fr));gap:10px}}
 .stat{{border:1px solid #dfe6f0;border-radius:8px;padding:10px 12px;background:#fbfcfe}}
 .stat strong{{display:block;font-size:22px}} .stat span{{font-size:12.5px;color:#4a5b73}}
 .hot{{background:#fde2e4}} .warm{{background:#fff3cd}} .ok{{background:#e3f6e8}} .info{{background:#eef3fa}}
 .note{{font-size:13px;color:#4a5b73}} footer{{font-size:12px;color:#4a5b73;padding:14px 18px}}
</style></head>
<body>
<header><h1>{esc(title)}</h1><p>Official-source re-check of the NFL register, read 2026-11-18. Research only; no wagering advice.</p></header>
<nav aria-label="Pack navigation">{nav}</nav>
<main>
{body}
</main>
<footer>{esc(BUILD_NOTE)}. Blank means not confirmed; it never means zero or available.</footer>
</body></html>
"""


def table(headers: list[str], rows: list[tuple[list[str], str]]) -> str:
    """rows: (cells already escaped, official source url). Every row must carry an official url."""
    for cells, url in rows:
        if not url:
            raise ValueError("row without official source link")
    thead = "".join(f"<th>{esc(h)}</th>" for h in headers)
    body = []
    for cells, url in rows:
        tds = "".join(f"<td>{c}</td>" for c in cells)
        body.append(f"<tr>{tds}<td>{link(url, 'nfl.com ↗' if 'nfl.com' in url else 'source ↗')}</td></tr>")
    return (f'<div class="table-wrap"><table><thead><tr>{thead}<th>Source</th></tr></thead>'
            f"<tbody>{''.join(body)}</tbody></table></div>")


def build() -> dict[str, str]:
    reads = load("official_reads.csv")
    read = {r["read_id"]: r for r in reads}
    slate = load("week11_slate.csv")
    byes = load("week11_byes.csv")
    claims = load("claim_checks.csv")
    club = load("club_depth_reads.csv")
    flags = load("flagged.csv")
    sugg = load("pack_suggestions.csv")
    qs = load("pack_questions.csv")
    sources = load("sources.csv")

    def official_url(ids: str) -> str:
        """First official nfl.com read URL among the pipe-joined read ids; '' if none."""
        for rid in [x for x in ids.split("|") if x]:
            r = read.get(rid)
            if r and r["host"] == "www.nfl.com":
                return r["url"]
        return ""

    def split_rows(items: list[tuple[list[str], str, str]]):
        """items: (cells, evidence_ids, extra_text). Rows with an nfl read go to the table; the rest to a list."""
        tab, lst = [], []
        for cells, ids, extra in items:
            url = official_url(ids)
            if url:
                tab.append((cells, url))
            else:
                lst.append(f"<li>{' · '.join(cells)}{(' — ' + esc(extra)) if extra else ''}</li>")
        return tab, lst

    def verdict_class(v: str) -> str:
        if v.startswith("CONSISTENT"):
            return "ok"
        if v.startswith("CONTRADICTED") or v.startswith("CONFLICT") or v.startswith("NOT CLEARED"):
            return "hot"
        return "warm"

    # ----- counts (all recomputed)
    venues_read = sum(1 for s in slate if s["venue_status"] == "read")
    chunk_done = sum(int(r["chunks_read"].split(" of ")[0]) for r in reads if r["read_id"] == "R01")
    chunk_total = sum(int(r["chunks_read"].split(" of ")[1]) for r in reads if r["read_id"] == "R01")
    nfl_reads = sum(1 for r in reads if r["host"] == "www.nfl.com")
    club_reads = len(reads) - nfl_reads
    cat = {"consistent": 0, "problem": 0, "not_reverified": 0}
    for c in claims:
        v = c["verdict"]
        if v.startswith("CONSISTENT"):
            cat["consistent"] += 1
        elif v.startswith(("CONTRADICTED", "CONFLICT", "NOT CLEARED")):
            cat["problem"] += 1
        elif v.startswith("NOT RE-VERIFIED"):
            cat["not_reverified"] += 1
    open_flags = sum(1 for f in flags if f["status"] == "open")
    awaiting = sum(1 for s in sugg if s["status"] == "awaiting_owner_choice")
    games = len(slate)
    clubs_playing = 2 * games
    bye_clubs = len(byes)

    pages: dict[str, str] = {}

    # ----- index
    readiness = [
        ("Week 11 injury report captured", "Route /injuries/2026/week-11 returns a page (not 404)",
         "0 of 1 published (404 at read time)", "R02"),
        ("Week 10 injury row counts (254 vs 279)", "All chunks of the Week 10 page read and counted",
         f"{chunk_done} of {chunk_total} chunks read", "R01"),
        ("Week 11 venues from game centres", "Every Week 11 venue read from its game centre",
         f"{venues_read} of {games} read", "R04|R05"),
        ("Ravens QB depth: date of change", "At least two dated depth captures plus the roster status",
         "1 dated read (2026-11-18); no history", "R12"),
        ("Malik Willis injured-reserve status", "Reserve list shows RES with a date",
         "RES dated 11/10 (Reserve/Injured)", "R06"),
        ("Colts receiver starter status (Downs, Allen)", "Official depth or snap evidence that names them as starters",
         "0 starter facts; trades dated 11/10 confirmed", "R07"),
        ("Azeez Al-Shaair: practice label versus reserve status", "One official designation source per player",
         "2 official pages, different label sets", "R06|R04"),
        ("Official depth order for Green Bay", "Official (not labelled Unofficial) depth page",
         "0 official pages found; club page labelled Unofficial", "R10"),
    ]
    rd_tab, rd_list = [], []
    for name, gate, number, ids in readiness:
        url = official_url(ids)
        cells = [esc(name), esc(gate), esc(number)]
        if url:
            rd_tab.append((cells, url))
        else:
            rd_list.append(f"<li>{esc(name)} — gate: {esc(gate)} — number: {esc(number)}</li>")
    stat = lambda label, value: f'<div class="stat"><strong>{esc(value)}</strong><span>{esc(label)}</span></div>'
    body = f"""
<section>
  <p class="eyebrow">2026-11-18 · WEEK 11 OPENS THURSDAY</p>
  <h2>What the official pages say today</h2>
  <p class="note">Each figure below is counted from the registers in this pack. Each read is dated to the 2026-11-18
  session window; the retrieval tool returns no per-request time.</p>
  <div class="grid">
    {stat("official nfl.com reads", nfl_reads)}
    {stat("club-website reads (outside the release-gate allowlist)", club_reads)}
    {stat("Week 11 games on the official schedule", games)}
    {stat("bye clubs (6 + 26 playing = 32)", bye_clubs)}
    {stat("Week 11 venues read from game centres", f"{venues_read} of {games}")}
    {stat("claims CONSISTENT with the live read", cat["consistent"])}
    {stat("claims CONTRADICTED, CONFLICT or NOT CLEARED", cat["problem"])}
    {stat("claims NOT RE-VERIFIED this session", cat["not_reverified"])}
    {stat("open flags (published, none blocks)", open_flags)}
    {stat("suggestions awaiting owner choice", awaiting)}
  </div>
</section>
<section>
  <h2>Decision readiness: one row per open item, the gate that blocks it, and the number that clears it</h2>
  {table(["Item", "Gate that blocks it", "Number now"], rd_tab)}
  {('<h3>Rows whose only evidence is a club website (outside the release-gate allowlist)</h3><ul>' + ''.join(rd_list) + '</ul>') if rd_list else ''}
  <p class="note">A row is shown in a table only when it links to an official nfl.com read.</p>
</section>
<section>
  <h2>Where to look next</h2>
  <div class="grid">
    <div class="stat"><strong><a href="week11.html">Week 11 slate</a></strong><span>13 games, venues read, 6 byes</span></div>
    <div class="stat"><strong><a href="claims.html">Claim checks</a></strong><span>repo and brief claims against the live reads</span></div>
    <div class="stat"><strong><a href="reads.html">Official reads</a></strong><span>verbatim excerpts with SHA-256 of the raw capture</span></div>
    <div class="stat"><strong><a href="club-depth.html">Club-site reads</a></strong><span>Packers and Ravens depth pages (not in the allowlist)</span></div>
    <div class="stat"><strong><a href="flagged.html">Flagged for Review</a></strong><span>irregularities, with the sources to check</span></div>
    <div class="stat"><strong><a href="suggestions.html">Suggestions</a></strong><span>options for the owner to choose; nothing implemented</span></div>
    <div class="stat"><strong><a href="questions.html">Questions</a></strong><span>what we have, what we lack, and the next route</span></div>
    <div class="stat"><strong><a href="sources.html">Sources</a></strong><span>each official URL with its read IDs</span></div>
  </div>
  <p class="note">Executive summary: <a href="{REPO_URL}/data/nfl_b2511a5c/README.md#executive-summary">data/nfl_b2511a5c/README.md, executive summary</a> ·
  register flags for manual review: <a href="{REPO_URL}/data/nfl_b2511a5c/flagged.csv">data/nfl_b2511a5c/flagged.csv</a>.</p>
</section>
"""
    pages["index.html"] = page("NFL official-source re-check (2026-11-18)", "index.html", body)

    # ----- week 11
    rows = []
    for s in slate:
        venue = s["venue"] if s["venue_status"] == "read" else "not read this session"
        rows.append(([esc(s["game_no"]), esc(s["matchup"]), esc(f'{s["weekday"]} {s["date_2026"]}'), esc(s["time_et"]),
                      esc(s["network"]), esc(f'{s["away"]} {s["away_record"]}'), esc(f'{s["home"]} {s["home_record"]}'),
                      esc(venue)], s["game_centre_url"]))
    bye_rows = [([esc(b["club"]), esc(b["club_name"]), esc(b["record"])], b["schedule_url"]) for b in byes]
    body = f"""
<section>
  <h2>Week 11 slate, as printed on the official schedule</h2>
  <p class="note">{games} games and {bye_clubs} bye clubs = {clubs_playing + bye_clubs} clubs. Records are the
  team records printed on the page at read time. A venue is shown only when its game centre was read; otherwise
  the cell says "not read this session". The matchup label is not a venue.</p>
  {table(["#", "Matchup", "Day, date", "Time (ET)", "Network", "Away", "Home", "Venue"], rows)}
</section>
<section>
  <h2>Teams on bye</h2>
  {table(["Club", "Name", "Record"], bye_rows)}
</section>
"""
    pages["week11.html"] = page("Week 11 slate (official schedule)", "week11.html", body)

    # ----- claims
    items = []
    for c in claims:
        cells = [esc(c["claim_id"]), esc(c["claim"]), esc(c["claim_origin"]),
                 f'<span class="{verdict_class(c["verdict"])}">{esc(c["verdict"])}</span>',
                 esc(c["live_observation"]), esc(c["live_read_ids"]), esc(c["next_step"])]
        items.append((cells, c["live_read_ids"], ""))
    tab, lst = split_rows(items)
    body = f"""
<section>
  <h2>Claim checks: the repo and the brief against the live official reads</h2>
  <p class="note">Each verdict is set against the read IDs in the next column (see the Official reads page).
  "CONSISTENT" means the live read agrees; it does not extend the claim beyond what was read.</p>
  {table(["ID", "Claim", "Origin", "Verdict", "Live observation", "Read IDs", "Next step"], tab)}
  {('<h3>Claims whose only evidence is a club website (see Club-site reads)</h3><ul>' + ''.join(lst) + '</ul>') if lst else ''}
</section>
"""
    pages["claims.html"] = page("Claim checks", "claims.html", body)

    # ----- reads
    tab_rows, club_reads_list = [], []
    for r in reads:
        if r["host"] != "www.nfl.com":
            continue
        cells = [esc(r["read_id"]), esc(r["page_title"]), esc(r["read_window_utc"]), esc(r["chunks_read"]),
                 esc(r["page_status"]), esc(r["used_for"]),
                 f'<code>{esc(r["raw_sha256"][:16])}…</code><br><span class="note">{esc(r["raw_file"])}</span>',
                 esc(" ⏐ ".join(p.strip() for p in r["expect"].split(" || ")))]
        tab_rows.append((cells, r["url"]))
    body = f"""
<section>
  <h2>Official nfl.com reads (verbatim excerpts)</h2>
  <p class="note">The raw captures are verbatim copies of the page text returned by the retrieval tool, with links stripped.
  They are not byte copies of the web page. The SHA-256 verifies the captured text only. The excerpts are checked
  as substrings of the raw captures by the verifier.</p>
  {table(["Read", "Page title as read", "Read window (UTC)", "Chunks", "Page status", "Used for", "Raw SHA-256 / file", "Verbatim excerpt(s)"], tab_rows)}
</section>
"""
    pages["reads.html"] = page("Official reads (nfl.com)", "reads.html", body)

    # ----- club-site reads (list only: outside the allowlist)
    club_list = []
    for r in reads:
        if r["host"] == "www.nfl.com":
            continue
        rows_here = [c for c in club if c["read_id"] == r["read_id"]]
        items_html = "".join(
            f"<li><strong>{esc(c['row'])}</strong>: {esc(c['cells'])} — {esc(c['observation'])} "
            f"<span class='note'>({esc(c['flag_id'])})</span></li>" for c in rows_here)
        club_list.append(
            f"<h3>{esc(r['read_id'])} · {esc(r['page_title'])}</h3>"
            f"<p>{link(r['url'])} · read window {esc(r['read_window_utc'])} · chunks {esc(r['chunks_read'])} · "
            f"used for: {esc(r['used_for'])}</p>"
            f"<p class='note'>Verbatim excerpt(s): {esc(' ⏐ '.join(p.strip() for p in r['expect'].split(' || ')))}</p>"
            f"<ul>{items_html}</ul>")
    body = f"""
<section>
  <h2>Club-website reads (not in the release-gate allowlist)</h2>
  <p class="note">The club websites are listed here as a list, not a table, because the repo's release gate
  (tools/release_gate.py OFFICIAL_HOSTS) allows only nfl.com and a few other hosts. Standing request logged in
  COORDINATION.md. Nothing on this page is a verified NFL designation.</p>
  {''.join(club_list)}
</section>
"""
    pages["club-depth.html"] = page("Club-website reads", "club-depth.html", body)

    # ----- flagged
    ftab, flist = [], []
    for f in flags:
        cells = [esc(f["flag_id"]), f'<span class="{ "hot" if f["severity"] == "high" else ("warm" if f["severity"] == "medium" else "info") }">{esc(f["severity"])}</span>',
                 esc(f["topic"]), esc(f["detail"]), esc(f["evidence_read_ids"]), esc(f["action_for_owner"]), esc(f["status"])]
        url = official_url(f["evidence_read_ids"])
        if url:
            ftab.append((cells, url))
        else:
            flist.append(f"<li><strong>{esc(f['flag_id'])}</strong> ({esc(f['severity'])}) {esc(f['topic'])}: {esc(f['detail'])} "
                         f"<span class='note'>Evidence: {esc(f['evidence_read_ids'])} · Action: {esc(f['action_for_owner'])}</span></li>")
    body = f"""
<section>
  <h2>Flagged for Review</h2>
  <p class="note">Published for the owner to review after the site is live. Flags do not block the merge. Each open flag
  states the owner action; none has been applied.</p>
  {table(["Flag", "Severity", "Topic", "Detail", "Evidence reads", "Action for owner", "Status"], ftab)}
  {('<h3>Flags whose only evidence is a club website or a repo file</h3><ul>' + ''.join(flist) + '</ul>') if flist else ''}
</section>
"""
    pages["flagged.html"] = page("Flagged for Review", "flagged.html", body)

    # ----- suggestions (options only; nothing implemented)
    evidence_for = {"S01": "R02", "S02": "R10", "S03": "R06|R07", "S04": "", "S05": "R11|R12", "S06": "R04|R05", "S07": "R01"}
    stab, slist = [], []
    for s in sugg:
        cells = [esc(s["suggestion_id"]), esc(s["theme"]), esc(s["suggestion"]), esc(s["options"]),
                 esc(s["evidence_needed"]), esc(s["status"]), "<span class='note'>(owner: blank)</span>"]
        url = official_url(evidence_for.get(s["suggestion_id"], ""))
        if url:
            stab.append((cells, url))
        else:
            slist.append(f"<li>{' · '.join(cells)}</li>")
    body = f"""
<section>
  <h2>Suggestions for the owner to choose from</h2>
  <p class="note">Nothing here is implemented. Each row lists the options; the owner chooses a path. The owner
  columns are blank on purpose.</p>
  {table(["ID", "Theme", "Suggestion", "Options", "Evidence needed", "Status", "Owner choice"], stab)}
  {('<h3>Suggestions whose evidence is a club website or a repo file</h3><ul>' + ''.join(slist) + '</ul>') if slist else ''}
</section>
"""
    pages["suggestions.html"] = page("Suggestions", "suggestions.html", body)

    # ----- questions
    qtab, qlist = [], []
    for q in qs:
        cells = [esc(q["q_id"]), esc(q["question"]), esc(q["we_have"]), esc(q["we_lack"]), esc(q["answer_now"]),
                 esc(q["read_ids"]), esc(q["next_route"])]
        url = official_url(q["read_ids"])
        if url:
            qtab.append((cells, url))
        else:
            qlist.append(f"<li>{' · '.join(cells)}</li>")
    body = f"""
<section>
  <h2>Questions, information and answers</h2>
  <p class="note">What the official reads answer today, what they do not, and the route to the missing piece.</p>
  {table(["ID", "Question", "What we have", "What we lack", "Answer now", "Read IDs", "Next route"], qtab)}
  {('<h3>Questions whose evidence is a club website or none</h3><ul>' + ''.join(qlist) + '</ul>') if qlist else ''}
</section>
"""
    pages["questions.html"] = page("Questions, information and answers", "questions.html", body)

    # ----- sources
    stab2, slist2 = [], []
    for s in sources:
        cells = [esc(s["source_id"]), esc(s["url"]), esc(s["host"]), esc(s["source_class"]), esc(s["read_ids"]), esc(s["used_for"])]
        if s["host"] == "www.nfl.com":
            stab2.append((cells, s["url"]))
        else:
            slist2.append(f"<li>{esc(s['source_id'])}: {link(s['url'])} · {esc(s['used_for'])}</li>")
    body = f"""
<section>
  <h2>Sources</h2>
  {table(["ID", "URL", "Host", "Class", "Read IDs", "Used for"], stab2)}
  {('<h3>Club websites (not in the release-gate allowlist)</h3><ul>' + ''.join(slist2) + '</ul>') if slist2 else ''}
</section>
"""
    pages["sources.html"] = page("Sources", "sources.html", body)
    return pages


def main() -> int:
    os.makedirs(DOCS, exist_ok=True)
    pages = build()
    for name, text in pages.items():
        with open(os.path.join(DOCS, name), "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print(f"wrote {len(pages)} pages to {os.path.relpath(DOCS, REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
