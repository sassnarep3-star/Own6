def chip(state: str) -> str:
    s = (state or "").lower()
    if s.startswith(("verified", "computed_from_verified", "implemented", "done")):
        cls, label = "verified", state
    elif s.startswith(("computed", "specified", "policy", "resolved")):
        cls, label = "computed", state
    elif s.startswith(("blocked", "absent", "no_club", "hypothesis")):
        cls, label = "blocked", state
    elif s.startswith(("unverified", "blank", "partial")):
        cls, label = "blank", state
    else:
        cls, label = "proposed", state
    return f'<span class="chip {cls}">{esc(label)}</span>'


def table(headers: list[str], rows: list[list[str]], numeric: set[int] | None = None,
          empty_cols: set[int] | None = None) -> str:
    numeric = numeric or set()
    empty_cols = empty_cols or set()
    out = ['<div class="tablewrap"><table><thead><tr>']
    for h in headers:
        out.append(f"<th scope=\"col\">{esc(h)}</th>")
    out.append("</tr></thead><tbody>")
    for r in rows:
        out.append("<tr>")
        for i, cell in enumerate(r):
            cls = []
            if i in numeric:
                cls.append("num")
            if i in empty_cols and (cell == "" or cell is None):
                cls.append("empty")
            attr = f' class="{" ".join(cls)}"' if cls else ""
            if i in empty_cols and (cell == "" or cell is None):
                out.append(f'<td{attr} aria-label="blank, unverified"></td>')
            else:
                out.append(f"<td{attr}>{cell}</td>")
        out.append("</tr>")
    out.append("</tbody></table></div>")
    return "".join(out)


