def _sd(xs: list[float]) -> float:
    m = sum(xs) / len(xs)
    return (sum((x - m) ** 2 for x in xs) / len(xs)) ** 0.5


def build_standings_aggregates() -> list[dict]:
    rows = read_csv("standings_2026_w11.csv")
    gp = [int(r["w"]) + int(r["l"]) + int(r["t"]) for r in rows]
    pf = [int(r["pf"]) for r in rows]
    pa = [int(r["pa"]) for r in rows]
    out = []

    def add(item, value, unit, derivation):
        out.append({
            "id": f"AGG-{len(out)+1:02d}",
            "item": item,
            "value": fmt(value, 4),
            "unit": unit,
            "derivation": derivation,
            "verification_status": "computed",
            "official_source": "NFL.com 2026 Division Standings (read 2026-11-13)",
            "official_source_url": OFFICIAL_STANDINGS,
        })

    add("League games played (sum of club games)", sum(gp) / 2, "games",
        "Two clubs play each game, so the sum of club games played is divided by 2.")
    add("Total points scored in the league", sum(pf), "points", "Sum of PF across all 32 clubs.")
    add("Mean points per team-game", sum(pf) / sum(gp), "points / team-game",
        "Sum of PF divided by sum of club games played.")
    add("Mean points allowed per team-game", sum(pa) / sum(gp), "points / team-game",
        "Sum of PA divided by sum of club games played. Equals the PF mean when the league is closed.")
    add("League points per game (two clubs)", 2 * sum(pf) / sum(gp), "points / game", "Two team-games per game.")
    add("Spread of club scoring (SD of points per game)", _sd([p / g for p, g in zip(pf, gp)]),
        "points / team-game", "Population standard deviation of each club's points per game.")
    add("Mean club point differential per game", sum(a - b for a, b in zip(pf, pa)) / sum(gp),
        "points / team-game", "Sum of (PF - PA) over sum of club games; 0 in a closed league.")
    add("Implied single-game margin SD (MODEL ASSUMPTION)",
        _sd([p / g for p, g in zip(pf, gp)]) * 2 ** 0.5, "points",
        "sqrt(2) x the club-level scoring SD. This is a modelling assumption, not an NFL statistic.")
    return out


def build_own_lines(aggregates: list[dict]) -> tuple[list[dict], float, float]:
    """Originated spread / total / win probability for every unplayed Week 10 game."""
    standings = {r["team"]: r for r in read_csv("standings_2026_w11.csv")}
    slate = [r for r in read_csv("slate.csv") if r["week"] == "10" and r.get("played_status") != "final"]
    sigma = float([a for a in aggregates if a["item"].startswith("Implied single-game")][0]["value"])
    league_ppg = float([a for a in aggregates if a["item"].startswith("League points per game")][0]["value"])
    out = []
    for g in slate:
        away, home = g["away_team"], g["home_team"]
        a, h = standings[away], standings[home]
        ag = int(a["w"]) + int(a["l"]) + int(a["t"])
        hg = int(h["w"]) + int(h["l"]) + int(h["t"])
        a_pf, a_pa = int(a["pf"]) / ag, int(a["pa"]) / ag
        h_pf, h_pa = int(h["pf"]) / hg, int(h["pa"]) / hg
        own_total = (h_pf + h_pa + a_pf + a_pa) / 2.0
        own_spread = ((h_pf + a_pa) - (a_pf + h_pa)) / 2.0
        p_home = model.win_prob_from_margin(own_spread, sigma)
        out.append({
            "game_id": g["game_id"], "matchup": g["matchup"],
            "kickoff_et": f"{g['game_date_et']} {g['kickoff_et']}",
            "away_games": ag, "home_games": hg,
            "away_pf_pg": fmt(a_pf), "away_pa_pg": fmt(a_pa),
            "home_pf_pg": fmt(h_pf), "home_pa_pg": fmt(h_pa),
            "own_total": fmt(own_total, 2), "own_spread_home": fmt(own_spread, 2),
            "own_win_prob_home": fmt(p_home, 4),
            "fair_ml_home": model.american_from_prob(p_home),
            "fair_ml_away": model.american_from_prob(1 - p_home),
            "sigma_used": fmt(sigma), "league_ppg_reference": fmt(league_ppg),
            "market_spread": "", "market_total": "", "market_ml_home": "", "market_ml_away": "",
            "edge_vs_market": "",
            "verification_status": "computed",
            "flags": "No market comparison (no licensed prices). No home-field term. No opponent adjustment.",
            "official_source": "NFL.com 2026 Division Standings + NFL.com Week 10 schedule",
            "official_source_url": OFFICIAL_STANDINGS,
            "second_source_url": OFFICIAL_SCHEDULE_10,
        })
    return out, sigma, league_ppg


def build_played_game_check(aggregates: list[dict]) -> dict:
    """Score the one finished Week 10 game against the same formulas, as an honesty check.

    The originated lines are *not* forecasts, so this is not a backtest. But a model that cannot
    come close on the single game that did finish has no business being extended to the other
    thirteen, and a reader deserves to see that number before trusting any of the rest.
    """
    standings = {r["team"]: r for r in read_csv("standings_2026_w11.csv")}
    final = [r for r in read_csv("slate.csv") if r.get("played_status") == "final"]
    if not final:
        return {}
    g = final[0]
    sigma = float([a for a in aggregates if a["item"].startswith("Implied single-game")][0]["value"])
    a, h = standings[g["away_team"]], standings[g["home_team"]]
    ag, hg = int(a["w"]) + int(a["l"]) + int(a["t"]), int(h["w"]) + int(h["l"]) + int(h["t"])
    a_pf, a_pa = int(a["pf"]) / ag, int(a["pa"]) / ag
    h_pf, h_pa = int(h["pf"]) / hg, int(h["pa"]) / hg
    own_total = (h_pf + h_pa + a_pf + a_pa) / 2.0
    own_spread = ((h_pf + a_pa) - (a_pf + h_pa)) / 2.0
    actual = g.get("final_score", "")
    try:
        away_pts, home_pts = [int(x.strip().split()[-1]) for x in actual.split(",")]
    except (ValueError, IndexError):
        return {}
    actual_margin = home_pts - away_pts          # positive = home won
    actual_total = home_pts + away_pts
    return {
        "game": g["matchup"], "score": actual, "date": g["game_date_et"],
        "model_own_total": fmt(own_total, 2), "actual_total": actual_total,
        "total_error": fmt(own_total - actual_total, 2),
        "model_own_spread_home": fmt(own_spread, 2), "actual_margin_home": actual_margin,
        "spread_error": fmt(own_spread - actual_margin, 2),
        "pick_correct": "home" if (own_spread > 0) == (actual_margin > 0) else "away",
        "source": OFFICIAL_SCHEDULE_10,
    }


def build_depth_deficiency() -> tuple[list[dict], list[dict]]:
    inj = read_csv("injuries_week10.csv")
    slate = {r["game_id"]: r for r in read_csv("slate.csv") if r["week"] == "10"}
    detail, summary = [], []
    teams: dict[str, list[dict]] = {}
    for r in inj:
        teams.setdefault(r["team"], []).append(r)

    for team in sorted(teams):
        chart = depthmod.CHART_SOURCES.get(team)
        rows = teams[team]
        agg = {"off_out": 0, "off_q": 0, "def_out": 0, "def_q": 0,
               "s2": 0, "s3": 0, "s4": 0, "unlisted": 0, "first_string_listed": 0}
        for r in rows:
            d, groups = depthmod.depth_index(team, r["player"]) if chart else (None, [])
            alias_note = ""
            if chart:
                for t, report_name, chart_name, note in depthmod.NAME_ALIASES:
                    if t == team and depthmod._norm(r["player"]) == depthmod._norm(report_name):
                        alias_note = f"matched to chart name '{chart_name}' — {note}"
            unit = depthmod.unit_of(r["position"])
            if chart is None:
                chart_status, dstr = "no_club_chart_read", ""
            elif d is None:
                chart_status, dstr = "not_listed_on_club_chart", ""
            else:
                chart_status, dstr = "listed", str(d)
            gs, ps = r["game_status"], r["practice_status"]
            avail = depthmod.availability(ps, gs)
            detail.append({
                "game_id": r["game_id"], "team": team, "matchup": slate[r["game_id"]]["matchup"],
                "player": r["player"], "position": r["position"], "unit": unit,
                "injury_reported": r["injury_reported"], "practice_status": ps, "game_status": gs,
                "declared_availability_weight": fmt(avail, 2),
                "club_chart_depth_string": dstr, "club_chart_groups": "; ".join(groups),
                "chart_status": chart_status, "name_match_note": alias_note,
                "displacement_note": _displacement_note(d, gs, ps, unit),
                "verification_status": "verified_inputs_computed_join",
                "official_source": "NFL.com official injury report (Week 10) + official club depth chart",
                "official_source_url": OFFICIAL_INJURIES,
                "depth_chart_url": chart["url"] if chart else "",
            })
            if chart is None:
                continue
            if d is None:
                agg["unlisted"] += 1
                continue
            if d == 1:
                agg["first_string_listed"] += 1
            if d == 1 and gs == "Out" and unit in ("offense", "defense"):
                agg["off_out" if unit == "offense" else "def_out"] += 1
            elif d == 1 and gs == "Questionable" and unit in ("offense", "defense"):
                agg["off_q" if unit == "offense" else "def_q"] += 1
            elif d == 2 and gs == "Out":
                agg["s2"] += 1
            elif d == 3 and gs == "Out":
                agg["s3"] += 1
            elif d == 4 and gs == "Out":
                agg["s4"] += 1
        if chart:
            summary.append({
                "team": team, "matchup": slate[rows[0]["game_id"]]["matchup"],
                "players_on_official_injury_report": len(rows),
                "first_string_listed_on_chart": agg["first_string_listed"],
                "off_first_string_ruled_out": agg["off_out"],
                "off_first_string_questionable": agg["off_q"],
                "def_first_string_ruled_out": agg["def_out"],
                "def_first_string_questionable": agg["def_q"],
                "second_string_ruled_out": agg["s2"],
                "third_string_ruled_out": agg["s3"],
                "fourth_string_ruled_out": agg["s4"],
                "listed_players_not_on_club_chart": agg["unlisted"],
                "deficiency_score": "",
                "score_note": "Deliberately blank: no official metric converts a lost starter into points.",
                "verification_status": "computed_from_verified_inputs",
                "official_source": "NFL.com official injury report (Week 10) + official club depth chart",
                "official_source_url": OFFICIAL_INJURIES,
                "depth_chart_url": chart["url"],
            })
    for gid in sorted({r["game_id"] for r in inj}):
        for team in (slate[gid]["away_team"], slate[gid]["home_team"]):
            if team in teams and team not in depthmod.CHART_SOURCES:
                summary.append({
                    "team": team, "matchup": slate[gid]["matchup"],
                    "players_on_official_injury_report": len(teams[team]),
                    "first_string_listed_on_chart": "",
                    "off_first_string_ruled_out": "", "off_first_string_questionable": "",
                    "def_first_string_ruled_out": "", "def_first_string_questionable": "",
                    "second_string_ruled_out": "", "third_string_ruled_out": "",
                    "fourth_string_ruled_out": "", "listed_players_not_on_club_chart": "",
                    "deficiency_score": "",
                    "score_note": "Blank: no club depth chart was read for this club, so the string is unknown. Not zero.",
                    "verification_status": "unverified_blank",
                    "official_source": "NFL.com official injury report (Week 10); no club chart read",
                    "official_source_url": OFFICIAL_INJURIES,
                    "depth_chart_url": "",
                })
    summary.sort(key=lambda r: r["team"])
    return detail, summary


def _displacement_note(d, gs, ps, unit):
    if d is None:
        return "Depth string unknown: cannot say whether a backup replaces a starter."
    if d == 1 and gs == "Out":
        return f"FIRST-STRING {unit} player ruled Out; the club chart lists a replacement behind him."
    if d == 1 and gs == "Questionable":
        return f"FIRST-STRING {unit} player Questionable; availability unresolved on this report."
    if d == 1:
        return "First-string player listed with no game status (not a statement that he will play)."
    if gs == "Out":
        return f"String-{d} player ruled Out; displaces no starter, so no deficiency signal."
    if not ps:
        return f"String-{d} player with no practice status recorded."
    return f"String-{d} player with a practice status recorded and no game status."


