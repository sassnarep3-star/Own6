def esc(v) -> str:
    return html.escape(str("" if v is None else v), quote=True)


def cell(v) -> str:
    v = "" if v is None else str(v)
    if not v.strip():
        return '<td class="blank">—</td>'
    return f"<td>{esc(v)}</td>"


def cell_url(url: str, label: str = "") -> str:
    if not url:
        return '<td class="blank">no link</td>'
    text = esc(label or (url.replace("https://", "")[:44] + ("…" if len(url) > 44 else "")))
    return f'<td><a href="{esc(url)}" rel="noopener">{text} ↗</a></td>'


def table(headers, rows) -> str:
    ths = "".join(f"<th scope=col>{esc(h)}</th>" for h in headers)
    body = []
    for r in rows:
        tds = "".join(c if c.startswith("<t") else f"<td>{esc(c)}</td>" for c in r)
        body.append(f"<tr>{tds}</tr>")
    return (f'<div class="table-wrap"><table><thead><tr>{ths}</tr></thead>'
            f"<tbody>{''.join(body)}</tbody></table></div>")


