    write_csv("questions_master.csv", questions)
    write_csv("decision_paths.csv", paths)
    write_csv("information_board.csv", board)
    write_csv("information_gaps.csv", gaps)
    write_csv("official_reads.csv", reads)
    write_csv("observations.csv", observations)
    write_csv("answers.csv", answers)
