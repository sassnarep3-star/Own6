def sources_csv(reads, inventory) -> list:
    out = []
    for r in reads:
        out.append({"source_id": f"SRC-{r['read_id']}", "class": "official_read_this_session",
                    "url": r["url"], "host": r["host"], "read_on_utc": r["read_window_utc"],
                    "used_for": r["purpose"], "raw_retained": "quoted text in official_reads.csv",
                    "hash": "", "path_or_row": ""})
    for i in inventory:
        out.append({"source_id": f"SRC-REG-{os.path.basename(i['path']).split('.')[0]}-{i['pack']}",
                    "class": "repo_register_inherited", "url": read_csv_rel(i["path"]),
                    "host": "github.com", "read_on_utc": "",
                    "used_for": f"{i['kind']} register from {i['pack']}",
                    "raw_retained": "file in repo", "hash": i["sha256"], "path_or_row": i["path"]})
    return out


